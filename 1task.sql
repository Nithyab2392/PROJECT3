WITH CTE AS (
    SELECT *,
           ROW_NUMBER() OVER (
               PARTITION BY order_id, restaurant_id, customer_id, order_date, order_time,
                            delivery_time, total_cost, item_count, payment_method, customer_rating
               ORDER BY order_id
           ) AS rn
    FROM Zomato_orders
)
SELECT * FROM CTE WHERE rn > 1;

WITH CTE AS (
    SELECT *,
           ROW_NUMBER() OVER (
               PARTITION BY restaurant_id, restaurant_name, city, area, cuisine,
                            avg_rating, total_ratings, price_range, delivery_available
               ORDER BY restaurant_id
           ) AS rn
    FROM Zomato_restaurants
    )
    SELECT * FROM CTE WHERE rn > 1;
    
    
# to replace null in restaurants  table
SELECT 
    restaurant_id,
ifnull(restaurant_name, 'Unknown') AS restaurant_name,
ifnull(city, 'Not Provided') AS city,
ifnull(avg_rating, 0) AS avg_rating,
ifnull(delivery_available, 'No') AS delivery_available
FROM Zomato_restaurants;


