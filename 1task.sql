# to find the count of cities

 SELECT city, COUNT(*) AS restaurant_count
FROM zomato_restaurants
GROUP BY city
ORDER BY restaurant_count DESC;


    #  	Find the top 5 cities with the highest number of orders.
  
SELECT r.city, COUNT(o.order_id) AS total_orders
FROM Zomato_orders as  o
JOIN Zomato_restaurants as r
    ON o.restaurant_id = r.restaurant_id
GROUP BY r.city
ORDER BY total_orders desc
limit 5 ;

 # 	Calculate the total revenue generated by each restaurant.

SELECT r.restaurant_id,
       r.restaurant_name,
      Round( SUM(o.total_cost)) AS total_revenue
FROM Zomato_orders o
JOIN Zomato_restaurants r
    ON o.restaurant_id = r.restaurant_id
GROUP BY r.restaurant_id, r.restaurant_name
ORDER BY total_revenue DESC;
  
# total revenue city wise (extra task ) 

SELECT r.city,
       ROUND(SUM(o.total_cost), 2) AS total_revenue
FROM Zomato_orders o
JOIN Zomato_restaurants r
    ON o.restaurant_id = r.restaurant_id
GROUP BY r.city
ORDER BY total_revenue DESC;









